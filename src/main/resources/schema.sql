CREATE TABLE IF NOT EXISTS t_tide_crew_shift (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crew_id BIGINT NOT NULL,
    shift_start TIMESTAMP NOT NULL,
