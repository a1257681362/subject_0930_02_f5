    scheduled_end TIMESTAMP NOT NULL,
    original_start TIMESTAMP NOT NULL,
    original_end TIMESTAMP NOT NULL,
    schedule_status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    published_by VARCHAR(64),
    published_time TIMESTAMP,
    change_reason VARCHAR(255),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tide_schedule_no UNIQUE (schedule_no),
    CONSTRAINT uk_tide_schedule_window UNIQUE (window_id)
);
CREATE INDEX IF NOT EXISTS idx_tide_schedule_equipment_time
