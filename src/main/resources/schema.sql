-- 换水设备：同一设备同一时间只能服务一口池（窗口可端点相接，不可重叠）。
CREATE TABLE IF NOT EXISTS t_tide_equipment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_code VARCHAR(32) NOT NULL,
    equipment_name VARCHAR(64) NOT NULL,
