-- 换水窗口：潮汐候选 → 减天气禁作 → 交班次 后形成的可执行窗口（含生成过程留痕）。
-- 统一半开口径；plan_date 恒等于 window_start 所在自然日，候选与可执行窗口同口径归属。
-- 状态 CANDIDATE（候选）/EXECUTABLE（可执行）/SCHEDULED（已排班）/CLOSED（临时关闭）。
-- 重算（潮表调整）对已排班/已关闭窗口冻结不动，只重建未排班窗口。
CREATE TABLE IF NOT EXISTS t_tide_window (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    window_no VARCHAR(48) NOT NULL,
    pond_id BIGINT NOT NULL,
    sea_area VARCHAR(64) NOT NULL,
    plan_date DATE NOT NULL,
    window_start TIMESTAMP NOT NULL,
    window_end TIMESTAMP NOT NULL,
    window_status VARCHAR(16) NOT NULL DEFAULT 'CANDIDATE',
    candidate_start TIMESTAMP NOT NULL,
    candidate_end TIMESTAMP NOT NULL,
    source_tide_point_id BIGINT,
    crew_id BIGINT,
    frozen_flag BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_reason VARCHAR(500),
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tide_window_no UNIQUE (window_no),
    CONSTRAINT chk_tide_window_range CHECK (window_end > window_start)
);
CREATE INDEX IF NOT EXISTS idx_tide_window_pond_time ON t_tide_window (pond_id, window_start, window_end);
CREATE INDEX IF NOT EXISTS idx_tide_window_date ON t_tide_window (plan_date);
CREATE INDEX IF NOT EXISTS idx_tide_window_status ON t_tide_window (window_status);

-- 换水排班单：一个可执行窗口一张单，绑定池、设备、班组。
-- 状态 DRAFT（草稿）/PUBLISHED（已发布）/ADJUST_PENDING（修改待审批）/RESCHEDULED（已顺延改期）/CANCELLED（已取消）。
