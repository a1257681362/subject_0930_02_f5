-- ============================================================
-- aqua-5 潮汐窗口换水排班
-- 海区潮汐表（高潮潮点+偏移）生成换水候选时间；
-- 叠加禁作天气（半开区间减法）与人员班次（半开区间交集）后形成可执行窗口；
-- 同一设备同一时间只能服务一口池（窗口可相接不重叠）；
-- 排班发布后修改走调度审批；自动顺延只追加不改原计划；
-- 临时关闭窗口向受影响班组发通知并留回执；所有修改保留证据。
-- 时间统一口径：所有窗口一律半开区间 [window_start, window_end)，
-- 归属日 plan_date = window_start 所在自然日（按 Asia/Shanghai 存储），
-- 候选生成与可执行窗口归属用同一函数同一边界口径。
-- ============================================================

-- 海区潮汐表：按海区+日期一行，导入即覆盖该海区当日潮点（先删后插，同事务留证）。
CREATE TABLE IF NOT EXISTS t_tide_table (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tide_table_no VARCHAR(40) NOT NULL,
    sea_area VARCHAR(64) NOT NULL,
    tide_date DATE NOT NULL,
    tide_type VARCHAR(16) NOT NULL DEFAULT 'SEMI_DIURNAL',
    source VARCHAR(128),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tide_table_no UNIQUE (tide_table_no),
    CONSTRAINT uk_tide_table_area_date UNIQUE (sea_area, tide_date)
);

-- 潮点：高/低潮时刻与潮高（厘米）。换水候选窗口由 HIGH 潮点前后偏移展开。
CREATE TABLE IF NOT EXISTS t_tide_point (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tide_table_id BIGINT NOT NULL,
    point_seq INT NOT NULL,
    point_type VARCHAR(16) NOT NULL,
    point_time TIMESTAMP NOT NULL,
    height_cm INT,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tide_point UNIQUE (tide_table_id, point_seq)
);
CREATE INDEX IF NOT EXISTS idx_tide_point_table ON t_tide_point (tide_table_id);

-- 换水候选展开参数（按海区一行）：换水取高潮前后可纳潮时段，
-- 候选窗口 = [高潮时刻 + before_minutes, 高潮时刻 + after_minutes)，半开。
CREATE TABLE IF NOT EXISTS t_tide_window_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sea_area VARCHAR(64) NOT NULL,
    rule_name VARCHAR(64) NOT NULL,
    target_point_type VARCHAR(16) NOT NULL DEFAULT 'HIGH',
    before_minutes INT NOT NULL DEFAULT 60,
    after_minutes INT NOT NULL DEFAULT 120,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_tide_window_rule_area UNIQUE (sea_area)
);

-- 禁作天气：按海区登记禁作时段（如台风/暴雨/雷电预警），半开 [ban_start, ban_end)。
-- 候选窗口减去全部禁作时段后才允许排班；命中即排除并在排除原因中说明。
CREATE TABLE IF NOT EXISTS t_tide_weather_ban (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sea_area VARCHAR(64) NOT NULL,
    ban_start TIMESTAMP NOT NULL,
    ban_end TIMESTAMP NOT NULL,
    weather_type VARCHAR(32) NOT NULL,
    reason VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT chk_tide_weather_ban_range CHECK (ban_end > ban_start)
);
CREATE INDEX IF NOT EXISTS idx_tide_weather_area_time ON t_tide_weather_ban (sea_area, ban_start, ban_end);

-- 班组：换水作业班组，通知与回执的接收对象。
CREATE TABLE IF NOT EXISTS t_tide_crew (
